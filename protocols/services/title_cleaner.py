# -*- coding: utf-8 -*-
"""
Очистка названий протоколов от служебных фраз (Федерация, Секция, ПРОТОКОЛ РЕЗУЛЬТАТОВ и т.п.).
Используется при отображении, в экспорте TXT (имя файла), в экспорте Excel (заголовки колонок).
"""

# Фразы, которые вырезаем из названия (без учёта регистра в начале)
NOISE_PHRASES = [
    'Федерация Спортивного Ориентирования г. Москвы',
    'Федерация спортивного ориентирования г. Москвы',
    'Секция Спортивного Ориентирования МИФИ',
    'Секция спортивного ориентирования МИФИ',
    'ПРОТОКОЛ РЕЗУЛЬТАТОВ',
    'Протокол результатов',
    'протокол результатов',
]


def clean_protocol_title(title: str) -> str:
    """
    Удаляет из названия протокола служебные фразы и лишние пробелы.
    title — исходное название (может быть пустым).
    Возвращает очищенную строку.
    """
    if not title or not isinstance(title, str):
        return title or ''
    text = title.strip()
    for phrase in NOISE_PHRASES:
        text = text.replace(phrase, ' ')
    return ' '.join(text.split()).strip()
